#!/usr/bin/env python3
"""Regenerate src/font.h from the system monospace font.

    python3 tools/genfont.py "$(fc-match -f '%{file}' monospace)" > src/font.h

Glyphs are rasterised without antialiasing into the tightest cell that fits
every printable ASCII character, one byte per row.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

path = sys.argv[1]
SIZE = 9
f = ImageFont.truetype(path, SIZE)
PAD_X, BASE = 4, 16
chars = [chr(i) for i in range(32, 127)]


def render(ch):
    img = Image.new("1", (20, 24), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = "1"
    d.text((PAD_X, BASE), ch, font=f, fill=1, anchor="ls")
    return img


x0, y0, x1, y1 = 99, 99, -1, -1
for ch in chars:
    bb = render(ch).getbbox()
    if bb:
        x0, y0 = min(x0, bb[0]), min(y0, bb[1])
        x1, y1 = max(x1, bb[2]), max(y1, bb[3])
W, H = x1 - x0, y1 - y0
assert W <= 8, f"cell too wide for a uint8 row: {W}"

print("/* Generated by tools/genfont.py - do not edit by hand.")
print(f" * Source: {path.split('/')[-1]} at {SIZE}px, cell {W}x{H}, ASCII 32-126. */")
print("#ifndef EVEO_FONT_H\n#define EVEO_FONT_H\n#include <stdint.h>\n")
print(f"#define FONT_W {W}\n#define FONT_H {H}\n#define FONT_FIRST 32\n#define FONT_LAST 126\n")
print("/* one byte per row, bit N set => pixel at column N */")
print(f"static const uint8_t font_glyphs[{len(chars)}][{H}] = {{")
for ch in chars:
    px = render(ch).load()
    rows = []
    for y in range(y0, y1):
        bits = 0
        for xx in range(x0, x1):
            if px[xx, y]:
                bits |= 1 << (xx - x0)
        rows.append(bits)
    name = ch if ch not in '\\\'"' else '\\' + ch
    print("    {" + ",".join("0x%02x" % r for r in rows) + f"}}, /* '{name}' */")
print("};\n\n#endif")
